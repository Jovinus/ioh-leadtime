#: A3's starting-score window.  Reused rather than redefined so the decile cross-tab is
#: against the published quantity.
START_SCORE_WINDOW_MIN = 30
#: Observable-run-up bands.  The cut points are A7's reporting thresholds.
LENGTH_BANDS = ((0, 20), (20, 40), (40, 60), (60, np.inf))
LENGTH_LABELS = ("<20", "20-39", "40-59", ">=60")
#: A crossing this many minutes or fewer into monitoring is called warm-up.  Chosen from
#: the score profile below -- every family has settled by then -- and reported as a
#: sensitivity alongside 3 and 10 minutes rather than relied on as a single cut.
WARMUP_MIN = 5
WARMUP_ALTERNATIVES = (3, 10)
#: How many minutes of the profile to tabulate from each record's first scored minute.
PROFILE_MIN = 16


def _case_features(family: str, cohort: str) -> pd.DataFrame:
    """One row per case: cluster, label, the two first-eligible-minute scores, the peak.

    ``peak`` is the maximum inside the published alert window, so ``peak >= threshold`` is
    exactly the published detection rule; the two ``first_*`` scores are what classify a
    detection once it has happened.
    """
    frame = load_scored(family, cohort)
    frame = frame[np.isfinite(frame["score"]) & (frame["t_to_event"] > 0)]
    window = frame[frame["t_to_event"] <= ALERT_WINDOW_MIN]

    def _first(group_frame: pd.DataFrame, name: str) -> pd.DataFrame:
        order = group_frame.sort_values("t_to_event", ascending=False)
        first = order.groupby("case_id", sort=False).first()
        return first[["score", "t_to_event"]].rename(
            columns={"score": f"first_score_{name}", "t_to_event": f"first_min_{name}"}
        )

    out = window.groupby("case_id").agg(
        cluster_id=("cluster_id", "first"),
        cluster_level=("cluster_level", "first"),
        label=("label", "first"),
        peak=("score", "max"),
        n_window_minutes=("score", "size"),
    )
    out = out.join(_first(window, "window")).join(_first(frame, "record"))
    start = frame[frame["t_to_event"] <= START_SCORE_WINDOW_MIN]
    out = out.join(_first(start, "start30").rename(
        columns={"first_score_start30": "start_score_30", "first_min_start30": "start_min_30"}
    ))
    return out.reset_index()


def _first_crossing(family: str, cohort: str, cut: float) -> pd.Series:
    """First chronological minute at or above ``cut``, as ``t_to_event``, per case."""
    window = alert_window(load_scored(family, cohort))
    crossings = window[window["score"] >= cut]
    return crossings.groupby("case_id")["t_to_event"].max()


def _record_start(family: str, cohort: str) -> pd.Series:
    """Each case's first scored minute, as ``t_to_event``.

    Subtracting a crossing's ``t_to_event`` from this gives the elapsed monitoring time at
    the crossing, which is what separates a warm-up crossing from a real one.
    """
    frame = load_scored(family, cohort)
    frame = frame[(frame["t_to_event"] > 0) & np.isfinite(frame["score"])]
    return frame.groupby("case_id")["t_to_event"].max()


def _score_profile(family: str, cohort: str) -> pd.DataFrame:
    """Median score by minutes elapsed since each record's first scored minute."""
    frame = load_scored(family, cohort)
    frame = frame[(frame["t_to_event"] > 0) & np.isfinite(frame["score"])]
    frame = frame.sort_values(["case_id", "t_to_event"], ascending=[True, False])
    frame = frame.assign(elapsed=frame.groupby("case_id").cumcount())
    frame = frame[frame["elapsed"] < PROFILE_MIN]
    out = (
        frame.groupby(["label", "elapsed"])["score"]
        .agg(["size", "median", "mean"])
        .reset_index()
        .rename(columns={"size": "n", "median": "score_median", "mean": "score_mean"})
    )
    out.insert(0, "family", family)
    out.insert(1, "cohort", cohort)
    return out


def _summarise_cell(
    features: pd.DataFrame,
    lead: pd.Series,
    start: pd.Series,
    cut: float,
    definition: str,
    family: str,
    cohort: str,
    target: float,
) -> dict:
    """One row: the prevalent/incident split and the leads, with paired bootstrap intervals."""
    frame = features.copy()
    frame["lead"] = frame["case_id"].map(lead)
    frame["record_start"] = frame["case_id"].map(start)
    frame["crossing_elapsed"] = frame["record_start"] - frame["lead"]
    frame["detected"] = frame["peak"] >= cut
    frame["prevalent"] = frame[f"first_score_{definition}"] >= cut

    events = frame[frame["label"] == 1].reset_index(drop=True)
    controls = frame[frame["label"] == 0].reset_index(drop=True)
    detected = events[events["detected"]].reset_index(drop=True)

    codes_d, n_clusters_d = cluster_codes(detected)
    rng = np.random.default_rng(seed_for("b1", family, cohort))
    weights_d = weight_matrix(n_clusters_d, rng, N_BOOTSTRAP_PATIENT) if n_clusters_d else None

    prevalent = detected["prevalent"].to_numpy(bool)
    lead_all = detected["lead"].to_numpy(float)

    row: dict = {
        "family": family,
        "family_label": FAMILY_LABELS[family],
        "cohort": cohort,
        "cohort_label": COHORT_LABELS[cohort],
        "target_sensitivity": target,
        "threshold": cut,
        "first_minute_definition": definition,
        "n_event_cases": int(len(events)),
        "n_detected": int(len(detected)),
        "n_prevalent": int(prevalent.sum()),
        "n_incident": int((~prevalent).sum()),
        "prop_prevalent": float(prevalent.mean()) if len(detected) else np.nan,
        "n_clusters_detected": int(n_clusters_d),
    }

    for name, mask in (("prevalent", prevalent), ("incident", ~prevalent), ("all", np.ones_like(prevalent))):
        values = lead_all[mask.astype(bool)]
        values = values[np.isfinite(values)]
        row[f"lead_median_{name}"] = float(np.median(values)) if values.size else np.nan
        row[f"lead_q25_{name}"] = float(np.percentile(values, 25)) if values.size else np.nan
        row[f"lead_q75_{name}"] = float(np.percentile(values, 75)) if values.size else np.nan
        row[f"lead_n_{name}"] = int(values.size)

    elapsed = detected["crossing_elapsed"].to_numpy(float)
    warmup = (~prevalent) & np.isfinite(elapsed) & (elapsed <= WARMUP_MIN)
    settled = (~prevalent) & ~warmup
    row["n_warmup"] = int(warmup.sum())
    row["prop_warmup"] = float(warmup.mean()) if len(detected) else np.nan
    row["n_settled"] = int(settled.sum())
    row["prop_settled"] = float(settled.mean()) if len(detected) else np.nan
    row["crossing_elapsed_median"] = float(np.nanmedian(elapsed)) if len(detected) else np.nan
    row["prop_crossing_within_warmup"] = (
        float(np.nanmean(elapsed <= WARMUP_MIN)) if len(detected) else np.nan
    )
    for alternative in WARMUP_ALTERNATIVES:
        row[f"prop_warmup_le_{alternative}"] = (
            float((((~prevalent) & np.isfinite(elapsed)) & (elapsed <= alternative)).mean())
            if len(detected) else np.nan
        )
    for name, mask in (("warmup", warmup), ("settled", settled)):
        values = lead_all[mask]
        values = values[np.isfinite(values)]
        row[f"lead_median_{name}"] = float(np.median(values)) if values.size else np.nan
        row[f"lead_q25_{name}"] = float(np.percentile(values, 25)) if values.size else np.nan
        row[f"lead_q75_{name}"] = float(np.percentile(values, 75)) if values.size else np.nan
        row[f"lead_n_{name}"] = int(values.size)

    if weights_d is not None and len(detected):
        prev_draws = np.empty(N_BOOTSTRAP_PATIENT)
        all_draws = np.empty(N_BOOTSTRAP_PATIENT)
        inc_draws = np.empty(N_BOOTSTRAP_PATIENT)
        set_draws = np.empty(N_BOOTSTRAP_PATIENT)
        warm_draws = np.empty(N_BOOTSTRAP_PATIENT)
        for replicate in range(N_BOOTSTRAP_PATIENT):
            w = weights_d[replicate][codes_d]
            prev_draws[replicate] = weighted_fraction(prevalent, w)
            all_draws[replicate] = weighted_median(lead_all, w)
            inc_draws[replicate] = weighted_median(lead_all, np.where(prevalent, 0, w))
            set_draws[replicate] = weighted_median(lead_all, np.where(settled, w, 0))
            warm_draws[replicate] = weighted_fraction(warmup, w)
        row["prop_prevalent_ci_lo"], row["prop_prevalent_ci_hi"] = percentile_ci(prev_draws)
        row["lead_median_all_ci_lo"], row["lead_median_all_ci_hi"] = percentile_ci(all_draws)
        row["lead_median_incident_ci_lo"], row["lead_median_incident_ci_hi"] = percentile_ci(inc_draws)
        # Paired: the same resampled clusters carry both medians, so this is the loss of
        # median lead attributable to removing prevalent alerts.
        diff = all_draws - inc_draws
        row["lead_shift_all_minus_incident"] = row["lead_median_all"] - row["lead_median_incident"]
        row["lead_shift_ci_lo"], row["lead_shift_ci_hi"] = percentile_ci(diff)
        row["lead_shift_p"] = bootstrap_p_two_sided(diff)
        row["prop_warmup_ci_lo"], row["prop_warmup_ci_hi"] = percentile_ci(warm_draws)
        row["lead_median_settled_ci_lo"], row["lead_median_settled_ci_hi"] = percentile_ci(set_draws)
        settled_diff = all_draws - set_draws
        row["lead_shift_all_minus_settled"] = row["lead_median_all"] - row["lead_median_settled"]
        row["lead_shift_settled_ci_lo"], row["lead_shift_settled_ci_hi"] = percentile_ci(settled_diff)
        row["lead_shift_settled_p"] = bootstrap_p_two_sided(settled_diff)
        row["lead_survival_fraction"] = (
            row["lead_median_incident"] / row["lead_median_all"]
            if row["lead_median_all"] not in (0, np.nan) and np.isfinite(row["lead_median_all"])
            else np.nan
        )

    # Control side.  A control "alerts prevalently" if it is above threshold at its own
    # first eligible minute -- a false alert produced by nothing that was observed.
    codes_c, n_clusters_c = cluster_codes(controls)
    rng_c = np.random.default_rng(seed_for("b1", family, cohort) + 1)
    control_prev = controls["prevalent"].to_numpy(bool)
    control_any = controls["detected"].to_numpy(bool)
    row["n_control_cases"] = int(len(controls))
    row["n_control_alerting"] = int(control_any.sum())
    row["prop_control_alerting"] = float(control_any.mean()) if len(controls) else np.nan
    row["n_control_prevalent"] = int(control_prev.sum())
    row["prop_control_prevalent"] = float(control_prev.mean()) if len(controls) else np.nan
    row["prop_control_prevalent_of_alerting"] = (
        float(control_prev.sum() / control_any.sum()) if control_any.sum() else np.nan
    )
    control_elapsed = controls["crossing_elapsed"].to_numpy(float)
    control_warm = control_any & (~control_prev) & np.isfinite(control_elapsed) & (
        control_elapsed <= WARMUP_MIN
    )
    row["n_control_warmup"] = int(control_warm.sum())
    row["prop_control_warmup"] = float(control_warm.mean()) if len(controls) else np.nan
    row["prop_control_prevalent_or_warmup_of_alerting"] = (
        float((control_prev | control_warm).sum() / control_any.sum())
        if control_any.sum() else np.nan
    )
    if n_clusters_c:
        weights_c = weight_matrix(n_clusters_c, rng_c, N_BOOTSTRAP_PATIENT)
        draws = np.array(
            [weighted_fraction(control_prev, weights_c[b][codes_c]) for b in range(N_BOOTSTRAP_PATIENT)]
        )
        row["prop_control_prevalent_ci_lo"], row["prop_control_prevalent_ci_hi"] = percentile_ci(draws)
    return row


def _crosstabs(features: pd.DataFrame, manifest: pd.DataFrame, lead: pd.Series, cut: float,
               definition: str, family: str, cohort: str, target: float) -> pd.DataFrame:
    """Prevalent fraction by observable-length band and by A3 starting-score decile."""
    frame = features.merge(
        manifest[["case_id", "observable_min"]], on="case_id", how="left"
    )
    frame = frame[(frame["label"] == 1) & (frame["peak"] >= cut)].copy()
    frame["lead"] = frame["case_id"].map(lead)
    frame["prevalent"] = frame[f"first_score_{definition}"] >= cut
    if frame.empty:
        return pd.DataFrame()

    rows: list[dict] = []
    band = pd.Series(pd.NA, index=frame.index, dtype="object")
    for (lo, hi), label in zip(LENGTH_BANDS, LENGTH_LABELS, strict=True):
        band[(frame["observable_min"] >= lo) & (frame["observable_min"] < hi)] = label
    frame["length_band"] = band
    for label in LENGTH_LABELS:
        cell = frame[frame["length_band"] == label]
        rows.append(
            {
                "stratifier": "observable_min_band",
                "stratum": label,
                "n_detected": int(len(cell)),
                "n_prevalent": int(cell["prevalent"].sum()),
                "prop_prevalent": float(cell["prevalent"].mean()) if len(cell) else np.nan,
                "lead_median_all": float(cell["lead"].median()) if len(cell) else np.nan,
            }
        )

    # A3's starting score is the score at the earliest observed minute of the 0-30 window.
    # Deciles are cut on every case in the cell, events and controls, so the decile edges
    # do not depend on who was detected.
    edges = features["start_score_30"].quantile(np.linspace(0, 1, 11)).to_numpy()
    edges = np.unique(edges)
    if edges.size >= 3:
        codes = np.clip(np.searchsorted(edges[1:-1], frame["start_score_30"].to_numpy(float), side="right"), 0, edges.size - 2)
        frame["start_decile"] = codes
        for decile in range(edges.size - 1):
            cell = frame[frame["start_decile"] == decile]
            rows.append(
                {
                    "stratifier": "start_score_30_decile",
                    "stratum": f"{decile + 1}",
                    "n_detected": int(len(cell)),
                    "n_prevalent": int(cell["prevalent"].sum()),
                    "prop_prevalent": float(cell["prevalent"].mean()) if len(cell) else np.nan,
                    "lead_median_all": float(cell["lead"].median()) if len(cell) else np.nan,
                    "start_score_lo": float(edges[decile]),
                    "start_score_hi": float(edges[decile + 1]),
                }
            )
    out = pd.DataFrame(rows)
    out.insert(0, "family", family)
    out.insert(1, "cohort", cohort)
    out.insert(2, "target_sensitivity", target)
    out.insert(3, "first_minute_definition", definition)
    return out


def run() -> dict[str, pd.DataFrame]:
    OUT.mkdir(parents=True, exist_ok=True)
    cuts = thresholds().set_index(["family", "target_sensitivity"])["threshold"]
    summaries: list[dict] = []
    crosstabs: list[pd.DataFrame] = []
    profiles: list[pd.DataFrame] = []
    for family in FAMILY_ORDER:
        for cohort in COHORT_ORDER:
            features = _case_features(family, cohort)
            manifest = case_manifest(cohort)
            start = _record_start(family, cohort)
            profiles.append(_score_profile(family, cohort))
            for target in TARGET_SENSITIVITIES:
                cut = float(cuts.loc[(family, target)])
                lead = _first_crossing(family, cohort, cut)
                for definition in ("window", "record"):
                    summaries.append(
                        _summarise_cell(features, lead, start, cut, definition, family, cohort, target)
                    )
                crosstabs.append(
                    _crosstabs(features, manifest, lead, cut, "window", family, cohort, target)
                )
            print(f"  b1 {family} / {cohort}", flush=True)
    tables = {
        "summary": pd.DataFrame(summaries),
        "crosstab": pd.concat([c for c in crosstabs if not c.empty], ignore_index=True),
        "score_profile": pd.concat(profiles, ignore_index=True),
    }
    for name, frame in tables.items():
        frame.to_csv(OUT / f"b1_{name}.csv", index=False)
    _write_report(tables)
    write_manifest(
        OUT,
        "b1_prevalent_incident",
        [],
        extra={
            "alert_window_min": ALERT_WINDOW_MIN,
            "alarm_rule": "case alerts iff score >= threshold at some minute in the window",
            "prevalent_definition": (
                "score at or above threshold at the case's first eligible scored minute; "
                "'window' takes that minute inside 0 < t_to_event <= 60, 'record' takes the "
                "first scored minute of the whole case"
            ),
            "thresholds": "validation-fixed, read from pre_submission_revision_2026, not reselected",
            "target_sensitivities": list(TARGET_SENSITIVITIES),
            "n_bootstrap": N_BOOTSTRAP_PATIENT,
            "seed_base": seed_for("b1", "transformer", "epic_test"),
            "start_score_window_min": START_SCORE_WINDOW_MIN,
            "warmup_min": WARMUP_MIN,
            "warmup_alternatives_min": list(WARMUP_ALTERNATIVES),
            "warmup_definition": (
                "an incident crossing whose elapsed monitoring time at the crossing is at "
                "most warmup_min minutes; incident by the letter of the definition, but "
                "produced by the input window filling rather than by any patient change"
            ),
        },
    )
    return tables


def _profile_wide(profile: pd.DataFrame) -> pd.DataFrame:
    """Median score at each elapsed minute, wide, with string column names for the table."""
    wide = (
        profile[profile["elapsed"] < 12]
        .pivot_table(index=["family", "cohort", "label"], columns="elapsed", values="score_median")
        .round(3)
    )
    wide.columns = [f"min {int(c)}" for c in wide.columns]
    return wide.reset_index()


def _write_report(tables: dict[str, pd.DataFrame]) -> None:
    summary = tables["summary"]
    head = summary[
        (summary["target_sensitivity"] == HEADLINE_TARGET)
        & (summary["first_minute_definition"] == "window")
    ]
    lines = [
        "# B1 - prevalent versus incident alerts\n",
        "A **prevalent** alert is a detected case whose score was already at or above the "
        "transported threshold at its first eligible scored minute: the alert reports a "
        "starting level, not an observed change. An **incident** alert crossed from below. "
        "Thresholds are the published validation-fixed ones, transported unchanged.\n",
        f"## 1. The headline split, {HEADLINE_TARGET:.0%} validation sensitivity target, "
        "first minute taken inside the 60-minute alert window\n",
    ]
    for cohort in COHORT_ORDER:
        cell = head[head["cohort"] == cohort]
        table = pd.DataFrame(
            {
                "Model": cell["family_label"],
                "Detected": cell["n_detected"],
                "Prevalent, n (%)": [
                    f"{int(r.n_prevalent)} ({r.prop_prevalent:.1%}"
                    f"; {r.prop_prevalent_ci_lo:.1%}–{r.prop_prevalent_ci_hi:.1%})"
                    for r in cell.itertuples()
                ],
                "Lead, prevalent, median (IQR)": [
                    f"{r.lead_median_prevalent:.0f} ({r.lead_q25_prevalent:.0f}–{r.lead_q75_prevalent:.0f})"
                    for r in cell.itertuples()
                ],
                "Lead, incident, median (IQR)": [
                    f"{r.lead_median_incident:.0f} ({r.lead_q25_incident:.0f}–{r.lead_q75_incident:.0f})"
                    for r in cell.itertuples()
                ],
                "Published lead (all detected)": [f"{r.lead_median_all:.0f}" for r in cell.itertuples()],
                "Lead, incident only (95% CI)": [
                    f"{r.lead_median_incident:.0f} ({r.lead_median_incident_ci_lo:.0f}–{r.lead_median_incident_ci_hi:.0f})"
                    for r in cell.itertuples()
                ],
                "Shift (95% CI)": [
                    f"{r.lead_shift_all_minus_incident:+.0f} ({r.lead_shift_ci_lo:+.0f} to {r.lead_shift_ci_hi:+.0f})"
                    for r in cell.itertuples()
                ],
                "Warm-up, n (%)": [
                    f"{int(r.n_warmup)} ({r.prop_warmup:.1%})" for r in cell.itertuples()
                ],
                "Lead, settled only (95% CI)": [
                    f"{r.lead_median_settled:.0f} ({r.lead_median_settled_ci_lo:.0f}–{r.lead_median_settled_ci_hi:.0f})"
                    for r in cell.itertuples()
                ],
            }
        )
        lines += [f"### {COHORT_LABELS[cohort]}\n", df_to_md(table), ""]

    lines += [
        "## 2. Where in the case the crossing happens, and the score profile that explains it\n",
        f"`crossing_elapsed_median` is the monitoring time already elapsed when the alert "
        f"fired. A **warm-up** crossing is an incident crossing at or before minute "
        f"{WARMUP_MIN} of monitoring: the score was genuinely below threshold at the first "
        "minute and above it later, so it is incident by definition, but the input window "
        "was filling rather than the patient changing. `settled` alerts are the remainder -- "
        "neither prevalent nor warm-up.\n",
        df_to_md(
            head[["cohort_label", "family_label", "n_detected", "crossing_elapsed_median",
                  "prop_prevalent", "prop_warmup", "prop_settled", "lead_median_all",
                  "lead_median_settled", "lead_shift_all_minus_settled"]].round(4)
        ),
        "",
        f"Sensitivity to the warm-up cut, at {WARMUP_ALTERNATIVES[0]} and "
        f"{WARMUP_ALTERNATIVES[1]} minutes:\n",
        df_to_md(
            head[["cohort_label", "family_label", "prop_warmup"]
                 + [f"prop_warmup_le_{a}" for a in WARMUP_ALTERNATIVES]].round(4)
        ),
        "",
        "Median score by minutes elapsed since each record's first scored minute. This is "
        "the evidence for the warm-up split, not an assumption behind it.\n",
        df_to_md(_profile_wide(tables["score_profile"])),
        "",
        "## 3. Controls\n",
        "`prop_control_prevalent` is the fraction of control cases already above threshold "
        "at their own first eligible minute -- a false alert no monitoring produced.\n",
    ]
    control = head[
        ["cohort_label", "family_label", "n_control_cases", "prop_control_alerting",
         "n_control_prevalent", "prop_control_prevalent", "prop_control_prevalent_of_alerting",
         "n_control_warmup", "prop_control_warmup",
         "prop_control_prevalent_or_warmup_of_alerting"]
    ]
    lines += [df_to_md(control), ""]

    lines += [
        "## 4. Sensitivity to the definition of the first eligible minute\n",
        "`record` takes the first scored minute of the whole case rather than of the "
        "60-minute window, so a long case is judged against a minute a real monitor would "
        "have seen.\n",
    ]
    both = summary[summary["target_sensitivity"] == HEADLINE_TARGET].pivot_table(
        index=["cohort_label", "family_label"],
        columns="first_minute_definition",
        values=["prop_prevalent", "lead_median_incident"],
    ).reset_index()
    both.columns = [" ".join(c).strip() for c in both.columns.to_flat_index()]
    lines += [df_to_md(both), ""]

    lines += [
        "## 5. All three sensitivity targets\n",
        df_to_md(
            summary[summary["first_minute_definition"] == "window"][
                ["cohort_label", "family_label", "target_sensitivity", "n_detected",
                 "prop_prevalent", "lead_median_all", "lead_median_incident",
                 "lead_shift_all_minus_incident", "prop_control_prevalent"]
            ]
        ),
        "",
        "## 6. Where the prevalent alerts sit\n",
        "By observable run-up length and by A3 starting-score decile, among detected event "
        "cases at the headline target. The decile relation is partly mechanical -- prevalence "
        "is defined by the level at the window's first minute, and the A3 starting score is "
        "the level at the first minute of the 30-minute window -- so it measures where "
        "prevalent alerts concentrate, not an independent association.\n",
        df_to_md(
            tables["crosstab"][tables["crosstab"]["target_sensitivity"] == HEADLINE_TARGET]
        ),
        "",
    ]
    (OUT / "b1_prevalent_incident.md").write_text("\n".join(lines), encoding="utf-8")


