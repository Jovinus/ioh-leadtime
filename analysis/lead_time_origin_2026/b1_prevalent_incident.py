"""B1 - is the reported alert lead time produced by a rise, or by the starting level?

Table 2 reports a 21-24 minute median alert lead at the 80% validation sensitivity target.
A6 reports that the entire median net score rise sits in the final 5 minutes. Both cannot
describe the same mechanism: a score whose net rise is confined to the last 5 minutes
cannot cross a fixed threshold 21 minutes out *by rising*. The candidate reconciliation is
that many detected cases were already above threshold at the first minute anyone looked at
them -- flagged on arrival, with no warning generated by any observed change.

So each detected case's first crossing is classified:

* **prevalent** - the score was already at or above threshold at the case's first eligible
  scored minute, so the "alert" is a statement about the starting level;
* **incident** - the score was below threshold at that first minute and crossed later, so
  the alert was generated by an observed change.

The published lead is then recomputed on incident alerts alone. What that number does is
the finding, in whichever direction it goes: if the prevalent fraction is small and the
lead survives, the contradiction dissolves and the lead-time reading stands.

Two definitions of "first eligible scored minute" are reported side by side, because the
choice is an analysis convention rather than a fact:

* ``window`` - the first minute inside the published alert window ``0 < t_to_event <= 60``.
  This is primary, because it is the first minute the published operating point scores.
* ``record`` - the first scored minute of the whole case, however far from onset. A case
  observed for three hours has a first minute a monitor would really have seen; under this
  definition a case can be incident in the window but prevalent on the record.

The control side is reported the same way. A control flagged at its own first eligible
minute is a false alert that no monitoring produced.

A third category turned up while this was being computed and is reported beside the other
two, because the prevalent/incident dichotomy does not exhaust the ways a lead time can be
manufactured. Every family's score behaves differently in the first minutes of a case,
when the input window holds only a few observations, than it does once the window has
filled. A crossing that happens two minutes into monitoring is *incident* by the letter of
the definition -- the score really was below threshold at the first minute and above it
later -- but nothing about the patient changed. So the elapsed monitoring time at the
crossing is recorded, incident crossings inside the first ``WARMUP_MIN`` minutes are split
out as **warm-up** crossings, and the median lead is recomputed a third time on the
crossings that are neither prevalent nor warm-up. The per-minute score profile from the
start of each record is written out as the evidence for the split rather than asserted.

Post-hoc on cached per-minute scores; no retraining, and no threshold is reselected.
"""

