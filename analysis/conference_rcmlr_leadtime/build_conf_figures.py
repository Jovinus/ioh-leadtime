"""Figures for the workshop paper.  Figure 1 is built here; Figure 2 comes from N1-N3.

NAMES HERE ARE ARTEFACT NAMES -- the ``Figure_<n>_wide`` filenames -- not the paper's
labels.  The two are deliberately decoupled (``latex/build_tex.py`` says why), and the
appendix was reordered on 2026-08-30, so the correspondence is worth stating once:
Figure_1 is the paper's Figure A2, Figure_2 is Figure 1, Figure_3 is Figure A4,
Figure_A2 is Figure A1, Figure_A3 is Figure A5, and Figure_A4 is Figure A3.

Figure 1 is the mechanism in one picture: median score against elapsed minutes since the
case's first scored minute, five families, event and control overlaid, with each family's
own transported alert threshold drawn as a horizontal rule.  Drawing the threshold on the
same axes is the whole point -- what separates the transformer from the rest is not the
shape of its early rise but whether that rise clears the cut the operating point uses.

Figure 3 is the prevalent / warm-up / settled composition, stacked, per family and cohort.
It appears in the paper as Figure A4; the filename is the artefact path and the label is
editorial, and ``latex/build_tex.py`` documents why the two are deliberately decoupled.

Figures A3 and A4 are the two event-aligned exhibits.  A3 puts the published population
trajectory beside the same bins recomputed on a cohort fixed to cases observable back to 60
minutes, with N(t) underneath, so a reader can attribute every widening interval to the
denominator rather than to the model; the plotting logic is adapted from
``analysis/lead_time_origin_2026/make_nt_figure.py``, whose ``_horizon`` and ``_crossing``
are reproduced here rather than imported because that module builds at screen size in
DejaVu Sans and importing it would pull its rcParams in with it.  A4 is the event-aligned
counterpart of Figure 2 on the same 3x5 grid -- the same score, the same families, the
other alignment -- so the two can be read side by side.

Figure 2 (lead against observed window, with the N2 shuffle band) is generated by
``analysis/lead_time_null_2026/make_figure_lead_vs_window.py`` and copied in, because it
needs the null distributions and belongs with the analysis that produced them.

Fonts are pinned to Times because the NeurIPS style uses ``ptm``.  matplotlib's default
DejaVu Serif is roughly 9% wider and silently inflates any layout estimate made from the
figure, and ``mathtext.fontset`` has to be set as well -- ``font.family`` alone leaves maths
in DejaVu Sans Oblique and embeds a second face.  Re-run the font audit in ``README.md``
after every regeneration.

Both a wide and a narrow width are written.  Scale by regenerating, never with
``\\includegraphics[height=]``: scaling shrinks every glyph and undoes the font pinning.
"""

