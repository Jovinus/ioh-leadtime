def figure_1(width: float, height: float, suffix: str) -> Path:
    k = width / TARGET_WIDTH_IN
    profile = pd.read_csv(B1 / "b1_score_profile.csv")
    profile = profile[profile["elapsed"] <= PROFILE_MAX_ELAPSED]
    cuts = headline_cuts()

    fig, axes = plt.subplots(
        len(COHORT_ORDER), len(FAMILY_ORDER),
        figsize=(width, height), sharex=True, sharey=True,
    )
    for row, cohort in enumerate(COHORT_ORDER):
        for column, family in enumerate(FAMILY_ORDER):
            ax = axes[row, column]
            cell = profile[(profile["family"] == family) & (profile["cohort"] == cohort)]
            for label, colour, name in ((1, EVENT, "event"), (0, CONTROL, "control")):
                part = cell[cell["label"] == label].sort_values("elapsed")
                ax.plot(part["elapsed"], part["score_median"], color=colour, lw=1.1,
                        marker="o", ms=1.8, label=name)
            cut = float(cuts[family])
            ax.axhline(cut, color=THRESHOLD, lw=0.8, ls=(0, (3, 2)))
            ax.set_ylim(0, 1.02)
            ax.set_xlim(0, PROFILE_MAX_ELAPSED)
            ax.set_xticks([0, 5, 10])
            ax.set_yticks([0, 0.5, 1.0])
            for side in ("top", "right"):
                ax.spines[side].set_visible(False)
            if row == 0:
                ax.set_title(FAMILY_LABELS[family], fontsize=6.8 * k, pad=3)
            if column == 0:
                ax.set_ylabel(ROW_LABELS[cohort], fontsize=6.2 * k)
            if row == len(COHORT_ORDER) - 1:
                ax.set_xlabel("Elapsed, min", fontsize=6.5 * k)
            ax.tick_params(labelsize=5.8 * k)
            if row == 0 and column == 0:
                handles, labels = ax.get_legend_handles_labels()
                handles.append(
                    Line2D([], [], color=THRESHOLD, lw=0.8, ls=(0, (3, 2)))
                )
                labels.append("alert threshold")
                ax.legend(handles, labels, loc="lower right", frameon=False,
                          fontsize=5.4 * k, handlelength=1.1, borderpad=0.1,
                          labelspacing=0.2)

    fig.text(0.004, 0.5, "Median score", va="center", rotation="vertical", fontsize=7 * k)
    fig.subplots_adjust(left=0.125, right=0.995, top=0.93, bottom=0.10,
                        hspace=0.22, wspace=0.14)

    path = OUT / f"Figure_1_{suffix}.pdf"
    fig.savefig(path)
    fig.savefig(OUT / f"Figure_1_{suffix}.png", dpi=PNG_DPI)
    plt.close(fig)
    return path


