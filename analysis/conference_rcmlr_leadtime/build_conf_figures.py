def horizon(cell: pd.DataFrame) -> float:
    """Farthest bin at which AUROC reaches 0.70, walking inward from 60 minutes.

    Reproduced from ``lead_time_origin_2026/make_nt_figure.py`` so the number drawn here and
    the number ``verify_numbers.py`` asserts come from one definition.
    """
    reached = cell[cell["auroc"] >= CLINICAL]
    return float(reached["bin_center_min"].max()) if len(reached) else np.nan


def crossing(all_cases: pd.DataFrame, fixed: pd.DataFrame) -> float:
    """Where the fixed-cohort curve falls back below the all-cases curve, by interpolation.

    Both series are read on the bins they share.  The reported crossing is the innermost sign
    change of ``fixed - all``, linearly interpolated between the two bracketing bin centres,
    because rounding it to a bin centre would overstate its precision.
    """
    merged = all_cases.merge(fixed, on="bin_center_min", suffixes=("_all", "_fixed"))
    merged = merged.sort_values("bin_center_min", ascending=False)
    difference = merged["auroc_fixed"].to_numpy() - merged["auroc_all"].to_numpy()
    centres = merged["bin_center_min"].to_numpy(float)
    for index in range(1, len(difference)):
        if difference[index - 1] > 0 >= difference[index]:
            span = difference[index - 1] - difference[index]
            if span == 0:
                return float(centres[index])
            fraction = difference[index - 1] / span
            return float(centres[index - 1] + fraction * (centres[index] - centres[index - 1]))
    return float("nan")


def figure_a3(width: float, height: float, suffix: str) -> Path:
    k = width / TARGET_WIDTH_IN
    frame = pd.read_csv(A7)
    series = {
        "all": ("All cases, denominator varies with the bin", ALL_CASES, "-", "o", True),
        FIXED_SAMPLE: ("Fixed cohort, observable back to 60 min", FIXED_COHORT,
                       (0, (3, 2)), "s", False),
    }

    # The AUROC row shares a scale because the comparison across cohorts is the point; the
    # N(t) row must not, because the three cohorts differ by a factor of two in size and a
    # shared axis flattens the smallest one into the floor.
    fig, axes = plt.subplots(
        2, len(COHORT_ORDER), figsize=(width, height), sharex=True,
        gridspec_kw={"height_ratios": [2.5, 1.0]},
    )
    for column, cohort in enumerate(COHORT_ORDER):
        top, bottom = axes[0, column], axes[1, column]
        cell = frame[frame["cohort"] == cohort]
        for sample, (name, colour, dash, marker, filled) in series.items():
            part = cell[cell["sample"] == sample].sort_values(
                "bin_center_min", ascending=False
            )
            x = part["bin_center_min"].to_numpy(float)
            top.fill_between(x, part["auroc_ci_lo"], part["auroc_ci_hi"],
                             color=colour, alpha=0.16, lw=0)
            top.plot(x, part["auroc"], color=colour, lw=1.1, ls=dash, marker=marker,
                     ms=2.2, mfc=colour if filled else "white", mew=0.7, label=name)
            bottom.plot(x, part["n_cases"], color=colour, lw=1.0, ls=dash, marker=marker,
                        ms=2.0, mfc=colour if filled else "white", mew=0.7)

        top.axhline(0.5, color=THRESHOLD, lw=0.5, ls=(0, (1, 2)))
        top.axhline(CLINICAL, color="#A93226", lw=0.7)
        # The crossing is the panel's claim, so it is marked. Its value, and both horizons,
        # are carried in the caption rather than annotated inline: at this width the callouts
        # from the screen-size version of this figure collide with the curves.
        at = crossing(cell[cell["sample"] == "all"], cell[cell["sample"] == FIXED_SAMPLE])
        if np.isfinite(at):
            top.plot([at], [np.interp(
                at,
                cell[cell["sample"] == "all"].sort_values("bin_center_min")["bin_center_min"],
                cell[cell["sample"] == "all"].sort_values("bin_center_min")["auroc"],
            )], marker="X", ms=3.6, color="#161C22", zorder=5)

        top.set_title(COHORT_LABELS[cohort], fontsize=7 * k, pad=3)
        top.set_ylim(0.44, 1.02)
        top.set_yticks([0.5, 0.7, 0.9])
        bottom.set_xlim(60, 0)
        bottom.set_xticks([60, 45, 30, 15, 0])
        bottom.set_xlabel("Minutes before onset", fontsize=6.5 * k)
        for ax in (top, bottom):
            for side in ("top", "right"):
                ax.spines[side].set_visible(False)
            ax.tick_params(labelsize=5.8 * k)
        if column == 0:
            top.set_ylabel("Population AUROC (95% CI)", fontsize=6.5 * k)
            bottom.set_ylabel("Cases in bin", fontsize=6.5 * k)
            top.legend(loc="upper left", frameon=False, fontsize=5.2 * k, handlelength=1.6,
                       borderpad=0.1, labelspacing=0.2)
        else:
            top.tick_params(labelleft=False)

    fig.subplots_adjust(left=0.085, right=0.995, top=0.92, bottom=0.13,
                        hspace=0.12, wspace=0.16)
    path = OUT / f"Figure_A3_{suffix}.pdf"
    fig.savefig(path)
    fig.savefig(OUT / f"Figure_A3_{suffix}.png", dpi=PNG_DPI)
    plt.close(fig)
    return path


def figure_a4(width: float, height: float, suffix: str) -> Path:
    k = width / TARGET_WIDTH_IN
    frame = pd.read_csv(A4)
    # The published 13-bin grid is the one the trend statistics are computed on. The bin at
    # onset is NaN by construction -- no minute is strictly before its own reference time --
    # so the series runs 60 to 5.
    frame = frame[(frame["grid"] == "published_13_bin") & frame["mean_score_event"].notna()]

    fig, axes = plt.subplots(
        len(COHORT_ORDER), len(FAMILY_ORDER),
        figsize=(width, height), sharex=True, sharey=True,
    )
    for row, cohort in enumerate(COHORT_ORDER):
        for column, family in enumerate(FAMILY_ORDER):
            ax = axes[row, column]
            cell = (
                frame[(frame["family"] == family) & (frame["cohort"] == cohort)]
                .sort_values("bin_center_min", ascending=False)
            )
            x = cell["bin_center_min"].to_numpy(float)
            for stem, colour, marker, filled, name in (
                ("event", EVENT, "o", True, "event"),
                ("control", CONTROL, "o", False, "control"),
            ):
                ax.fill_between(x, cell[f"mean_score_{stem}_ci_lo"],
                                cell[f"mean_score_{stem}_ci_hi"],
                                color=colour, alpha=0.18, lw=0)
                ax.plot(x, cell[f"mean_score_{stem}"], color=colour, lw=1.1, marker=marker,
                        ms=1.8, mfc=colour if filled else "white", mew=0.6, label=name)
            ax.set_ylim(0, 1.02)
            ax.set_xlim(60, 0)
            ax.set_xticks([60, 30, 0])
            ax.set_yticks([0, 0.5, 1.0])
            for side in ("top", "right"):
                ax.spines[side].set_visible(False)
            if row == 0:
                ax.set_title(FAMILY_LABELS[family], fontsize=6.8 * k, pad=3)
            if column == 0:
                ax.set_ylabel(ROW_LABELS[cohort], fontsize=6.2 * k)
            if row == len(COHORT_ORDER) - 1:
                ax.set_xlabel("Min before onset", fontsize=6.5 * k)
            ax.tick_params(labelsize=5.8 * k)
            if row == 0 and column == 0:
                ax.legend(loc="upper left", frameon=False, fontsize=5.4 * k,
                          handlelength=1.1, borderpad=0.1, labelspacing=0.2)

    fig.text(0.004, 0.5, "Mean score (95% CI)", va="center", rotation="vertical", fontsize=7 * k)
    fig.subplots_adjust(left=0.125, right=0.995, top=0.93, bottom=0.10,
                        hspace=0.22, wspace=0.14)
    path = OUT / f"Figure_A4_{suffix}.pdf"
    fig.savefig(path)
    fig.savefig(OUT / f"Figure_A4_{suffix}.png", dpi=PNG_DPI)
    plt.close(fig)
    return path


